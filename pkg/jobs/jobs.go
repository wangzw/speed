// Package jobs declares the job-execution capability for a distributed
// deployment: a piece of work to do at a later time, or to do away from the
// request path, is handed in as a durable job record and run by whichever
// replica claims it.
//
// One job table carries three needs at once — run once at a future instant,
// repeat every interval, and run a slow piece of work asynchronously. The
// submitting side depends only on the submission seam, Queue; the executing
// side is a business module that registers a Handler.
//
// This is the interface package. It registers no module and imports nothing of
// this repository: a module that only submits a job depends on this package
// alone, without carrying storage or the tenant roster. The queue and the
// registration face are delivered exclusively by pkg/jobs/db, which holds the
// job table and drives the consumers; periodic scheduling is pkg/jobs/scheduler,
// which enqueues on a tick from the Schedule declarations business modules
// place in their own resources.
//
// The capability carries only the triggers whose effect must converge across
// replicas. A loop that each replica runs for itself — refreshing an in-process
// snapshot, sweeping expired rows, rotating a file, polling an external state —
// is not this capability's: it belongs to the module that needs it, as its own
// ticker. The judge is whether the work has to happen once for the whole
// platform, not whether it is asynchronous.
package jobs

import (
	"context"
	"errors"
	"time"
)

// JobID identifies one job. It is generated by the application when the job is
// enqueued, and Get and Cancel address a job by it.
type JobID string

// Status is the state of a job. Its values are a closed set with a lifecycle
// meaning: pending, running and retrying are not terminal, while succeeded,
// dead_letter and cancelled are; Terminal reports which.
//
// The persistent form of a status is the same string as the constant below, so
// an operator reading the job table sees exactly these values.
type Status string

const (
	// StatusPending is a job that has not been claimed yet: it waits for its
	// time to come. A delayed job and a scheduled-once job both sit here until
	// they are due.
	StatusPending Status = "pending"
	// StatusRunning is a job a replica has claimed and is executing.
	StatusRunning Status = "running"
	// StatusRetrying is a job that failed and is waiting for its backoff to
	// elapse before it can be claimed again.
	StatusRetrying Status = "retrying"
	// StatusSucceeded is a job whose handler returned without error. It is
	// terminal.
	StatusSucceeded Status = "succeeded"
	// StatusDeadLetter is a job whose handler kept failing past its retry
	// limit. It is terminal, and it stays in the table until an operator deals
	// with it.
	StatusDeadLetter Status = "dead_letter"
	// StatusCancelled is a job that was cancelled. It is terminal.
	StatusCancelled Status = "cancelled"
)

// Terminal reports whether s is a status a job never leaves. It is true for
// StatusSucceeded, StatusDeadLetter and StatusCancelled, and false for the
// rest.
func (s Status) Terminal() bool {
	switch s {
	case StatusSucceeded, StatusDeadLetter, StatusCancelled:
		return true
	default:
		return false
	}
}

// Priority orders the claim. Its values are a closed set, and a job is claimed
// ahead of the lower priorities: PriorityHigh first, then PriorityNormal, then
// PriorityLow.
//
// Zero is a valid priority, so a job's priority is PriorityNormal unless the
// caller says otherwise; PriorityLow is the type's zero value and appears only
// when a caller passes Priority(0) explicitly. A caller therefore cannot get
// PriorityLow by saying nothing.
type Priority int

const (
	// PriorityLow is the lowest claim priority.
	PriorityLow Priority = 0
	// PriorityNormal is the priority a job takes when Enqueue is given no
	// WithPriority.
	PriorityNormal Priority = 5
	// PriorityHigh is the highest claim priority.
	PriorityHigh Priority = 10
)

// Task is one piece of work a caller hands in.
//
// It carries no tenant: the tenant is a fact about the calling context, read
// through tenant.FromContext, so a job belongs to whichever tenant the request
// or background path that submitted it was in. Writing the tenant into a Task
// field would create a second source that can disagree with the context.
type Task struct {
	// Type names the kind of job, chosen by the caller. It has to match the
	// Type of a registered Handler, or Enqueue refuses the task with
	// ErrNoHandler.
	Type string
	// Payload is the job's data. It is opaque to this capability, which stores
	// it and never interprets it or dispatches on it.
	Payload []byte
	// IdempotencyKey, when non-empty, makes Enqueue idempotent: a second
	// submission with the same key from the same tenant returns the existing
	// job's identifier instead of writing a second row.
	IdempotencyKey string
}

// Result is what a handler hands back once it has done the work. This
// capability only stores it and reports it back through Get; it does not
// deliver it anywhere and does not replay it.
type Result struct {
	Data []byte
}

// Job is the read-only view of one job.
//
// Its fields mirror the columns of the job table. The tenant is not a field
// here: it is carried by the persistence row, which embeds the tenant model, and
// the view a caller reads back is already scoped to the tenant of the context it
// was fetched in.
type Job struct {
	// ID identifies the job.
	ID JobID
	// Type names the kind of job, matching the registered handler's Type.
	Type string
	// Status is the job's state.
	Status Status
	// Priority is the job's claim priority.
	Priority Priority
	// Payload is the data the caller submitted.
	Payload []byte
	// Result is what the handler returned on success, and nil until then.
	Result *Result
	// Error is the text of the job's most recent failure, and empty for a job
	// that has not failed or has since succeeded.
	Error string
	// Attempts is how many times the job has been handed to a handler.
	Attempts int
	// MaxRetries is the job's retry limit: once Attempts passes it, a further
	// failure sends the job to dead_letter.
	MaxRetries int
	// Timeout is the limit on a single execution.
	Timeout time.Duration
	// ProgressPct is the last integer percentage the handler reported through
	// its ProgressFn.
	ProgressPct int
	// ProgressMsg is the last text the handler reported through its ProgressFn.
	ProgressMsg string
	// ScheduledAt is when the caller asked the job to run.
	ScheduledAt time.Time
	// StartedAt is when the most recent execution began, and nil before the
	// first one.
	StartedAt *time.Time
	// CompletedAt is when the job reached a terminal status, and nil until then.
	CompletedAt *time.Time
	// CreatedAt is when the row was written.
	CreatedAt time.Time
	// UpdatedAt is when the row was last changed.
	UpdatedAt time.Time
}

// ProgressFn reports execution progress from inside a handler: an integer
// percentage and a message. A queue records the most recent report on the job
// row.
type ProgressFn func(pct int, msg string)

// Handler executes one kind of job. A module that wants its jobs run registers
// one with the Handlers face in its Init.
//
// A handler must be safe to call concurrently, because executions run on more
// than one goroutine. It reports progress through the ProgressFn it is given,
// and returns a non-nil error to report a failure; the queue then retries with
// backoff or, past the job's MaxRetries, sends the job to dead_letter.
type Handler interface {
	// Type reports the job type this handler executes. It is registered under
	// this name and dispatched by it.
	Type() string
	// Handle runs one job. A non-nil error is a failed execution.
	Handle(ctx context.Context, job *Job, progress ProgressFn) (Result, error)
}

// Queue is the portable submission face: any module that hands work to the
// background depends on this and nothing more.
//
// A queue is delivered exclusively, so one backend is in force per process. Its
// methods may be called from more than one goroutine at once. Every method
// returns ErrNotRunning before the queue's start stage and after its stop
// stage.
type Queue interface {
	// Enqueue writes one job and returns its identifier.
	//
	// It validates the task's shape and refuses an invalid one with
	// ErrInvalidTask, and refuses a task whose Type has no registered handler
	// with ErrNoHandler, writing nothing in either case. The tenant comes from
	// ctx. When IdempotencyKey is non-empty, a second submission with the same
	// key from the same tenant returns the existing job's identifier rather
	// than writing a second row.
	Enqueue(ctx context.Context, t Task, opts ...EnqueueOption) (JobID, error)
	// Get returns one job visible to the tenant of ctx. An unknown identifier,
	// another tenant's identifier and an identifier that is no longer visible
	// are all reported as ErrJobNotFound alike, so that existence does not
	// leak.
	Get(ctx context.Context, id JobID) (*Job, error)
	// Cancel asks for a job to be cancelled, by the job's current status. An
	// unclaimed job is moved straight to cancelled; a claimed job only has a
	// cancellation requested, which the claimant observes before it executes it
	// and then settles as cancelled; a job already in a terminal status is an
	// idempotent no-op that changes nothing and returns nil. A job the tenant
	// cannot see is ErrJobNotFound.
	Cancel(ctx context.Context, id JobID) error
}

// Handlers is the registration face: a module that has jobs to run registers
// its handler here in its Init, which runs before the queue starts, so the
// handler set is fixed by the time any job executes.
//
// It is delivered by the same module as Queue, and exclusively with it.
type Handlers interface {
	// Register registers h under its Type. Registering the same type twice,
	// registering a handler whose Type is empty, registering nil, or
	// registering after the queue has started are all refused with an error and
	// leave the handler set unchanged.
	Register(h Handler) error
	// Registered lists the types that have been registered. It returns a
	// read-only slice, which a consumer uses to check at startup that a type it
	// declared — a Schedule's Type, say — is actually registered.
	Registered() []string
}

// enqueueOptions is the set of parameters one Enqueue call carries, as the With
// values build it. Its fields are exported so the queue backend that applies
// them, in a subpackage, can read them; the type itself is not part of this
// package's contract and is reached only through NewEnqueueOptions and the
// With constructors.
type enqueueOptions struct {
	// Priority is the job's priority. NewEnqueueOptions sets it to
	// PriorityNormal, and it becomes the type's zero value PriorityLow only
	// when a caller passes Priority(0) through WithPriority.
	Priority Priority
	// ScheduledAt is the earliest time the job may be claimed. The zero value
	// means "as soon as the enqueue writes the row".
	ScheduledAt time.Time
	// MaxRetries is the job's retry limit. NewEnqueueOptions sets it to
	// DefaultMaxRetries.
	MaxRetries int
	// Timeout is the limit on a single execution. NewEnqueueOptions sets it to
	// DefaultTimeout.
	Timeout time.Duration
}

// EnqueueOption sets one parameter of an Enqueue call. The With constructors
// below build them, and a queue applies them in the order the caller passed
// them.
type EnqueueOption func(*enqueueOptions)

// NewEnqueueOptions returns the parameters an Enqueue call starts from, before
// any option is applied: PriorityNormal, DefaultMaxRetries and DefaultTimeout,
// with no scheduled time. A queue backend calls it and then applies the
// options the caller passed.
func NewEnqueueOptions() *enqueueOptions {
	return &enqueueOptions{
		Priority:   PriorityNormal,
		MaxRetries: DefaultMaxRetries,
		Timeout:    DefaultTimeout,
	}
}

// WithPriority sets the job's Priority. Without it a job is PriorityNormal.
func WithPriority(p Priority) EnqueueOption {
	return func(o *enqueueOptions) { o.Priority = p }
}

// WithDelay makes the job eligible to be claimed a duration from now.
//
// It sets the same parameter as WithScheduledAt, so the two are mutually
// exclusive and the one applied last wins.
func WithDelay(d time.Duration) EnqueueOption {
	return func(o *enqueueOptions) { o.ScheduledAt = time.Now().Add(d) }
}

// WithScheduledAt makes the job eligible to be claimed no earlier than t.
//
// It sets the same parameter as WithDelay, so the two are mutually exclusive
// and the one applied last wins.
func WithScheduledAt(t time.Time) EnqueueOption {
	return func(o *enqueueOptions) { o.ScheduledAt = t }
}

// WithMaxRetries sets how many times the job may fail before it is sent to
// dead_letter. Without it a job gets DefaultMaxRetries.
func WithMaxRetries(n int) EnqueueOption {
	return func(o *enqueueOptions) { o.MaxRetries = n }
}

// WithTimeout sets the limit on a single execution. Without it a job gets
// DefaultTimeout.
func WithTimeout(d time.Duration) EnqueueOption {
	return func(o *enqueueOptions) { o.Timeout = d }
}

const (
	// DefaultMaxRetries is the retry limit a job takes when Enqueue is given no
	// WithMaxRetries. With it a job runs at most four times by default: the
	// initial attempt and three retries.
	DefaultMaxRetries = 3
	// DefaultTimeout is the limit on a single execution a job takes when
	// Enqueue is given no WithTimeout.
	DefaultTimeout = 5 * time.Minute
)

// The sentinels a caller decides on with errors.Is. A queue backend wraps them
// with %w, so the same identity answers on either side of the seam.
var (
	// ErrJobNotFound reports a Get or Cancel that named a job this tenant
	// cannot see: an unknown identifier, another tenant's identifier, and an
	// identifier that is no longer visible are all reported the same way, so
	// that a caller cannot tell them apart and the existence of another
	// tenant's job does not leak.
	ErrJobNotFound = errors.New("jobs: no job with that identifier is visible to this tenant")
	// ErrInvalidTask reports a Task whose shape is not valid, such as an empty
	// Type. Enqueue writes nothing when it refuses one.
	ErrInvalidTask = errors.New("jobs: the task is not a valid shape")
	// ErrNoHandler reports an Enqueue whose task Type has no registered
	// handler. Enqueue writes nothing when it refuses one.
	ErrNoHandler = errors.New("jobs: no handler is registered for the task's type")
	// ErrNotRunning reports a queue call made outside the queue's service: before
	// its start stage, or after its stop stage.
	ErrNotRunning = errors.New("jobs: the queue is not running")
)
