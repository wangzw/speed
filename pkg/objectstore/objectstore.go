// Package objectstore stores an object's bytes and carries its metadata
// through a lifecycle.
//
// It is the object-storage capability on its own: a caller declares an object,
// uploads its bytes, completes it, and from then on reads, lists and deletes it
// by identifier. The bytes live behind one seam, Store, and the metadata and
// lifecycle live behind another, Objects. This root package is the interface
// package: it carries both seams, the common types, the audit action type names
// and the sentinels, and registers no module.
//
// Payload and key alike are this capability's own concern. An object's bytes are
// located by an internal key whose syntax this capability fixes, generates and
// never exposes: a caller addresses an object by its identifier, not by its key,
// and Store is the only way bytes move. The module that delivers Objects imports
// no backend SDK, so a host that installs one backend carries that backend
// alone.
//
// A backend is a module. An implementation subpackage hands a Spec to NewModule
// and a host enables at most one of them, because the byte seam is delivered
// exclusively: one process has exactly one answer to where an object's bytes
// land. The metadata surface is a module of its own, delivered by
// pkg/objectstore/metadata.
package objectstore

import (
	"context"
	"errors"
	"io"
	"time"
)

// Store is the byte seam: an object's bytes move through it. The internal key
// that addresses them is generated by the module that delivers Objects; this
// seam promises nothing about its syntax, and an implementation only maps it to
// wherever its own backend keeps bytes.
//
// Every method reaches its backend and returns once that backend has answered.
// There is no queue and no retry: a backend that is unreachable fails the call,
// and whether to try again is the caller's to decide.
type Store interface {
	// Name reports the implementation's name, for diagnostics.
	Name() string
	// Put stores size bytes read from r under key. The reader is read once; an
	// implementation does not hold onto it past the call.
	Put(ctx context.Context, key string, r io.Reader, size int64) error
	// Open returns a read-only stream over the bytes stored under key. The
	// caller closes it.
	Open(ctx context.Context, key string) (io.ReadCloser, error)
	// Delete removes the bytes stored under key. It is idempotent: deleting
	// bytes that are not there is not an error.
	Delete(ctx context.Context, key string) error
}

// State is where an object stands in its lifecycle. The set is closed: an
// object is in exactly one of these states.
type State string

const (
	// StatePending is an object that has been declared and whose upload window
	// has not yet closed.
	StatePending State = "pending"
	// StateUploaded is an object whose bytes have arrived and that is waiting to
	// be completed.
	StateUploaded State = "uploaded"
	// StateCompleted is an object that can be read.
	StateCompleted State = "completed"
	// StateDeleted is an object whose metadata row is kept as a tombstone and
	// whose bytes have been removed from the backend.
	StateDeleted State = "deleted"
)

// Object is one object's view, as the metadata seam hands it out.
//
// The declared values a caller gave and the observed values the capability read
// from the bytes are kept apart in the table, and this view carries the observed
// side: Size and Checksum are what an upload recorded, not what a declaration
// promised.
//
// The tenant dimension is carried by the table row's embedded tenant.Model; a
// view carries no tenant column, because a caller only ever sees objects of its
// own tenant.
type Object struct {
	// ID is the object identifier a caller addresses it by.
	ID string
	// Key is the internal key the bytes are stored under. It is module
	// bookkeeping: it reaches no API response, no error text and no log line.
	Key string
	// State is where the object stands in its lifecycle.
	State State
	// Size is the number of bytes observed at upload. It is zero before an
	// upload.
	Size int64
	// MIME is the content type recorded at upload, taken from the declaration.
	MIME string
	// Checksum is the SHA-256 recorded at upload, computed from the bytes. It is
	// empty before an upload.
	Checksum string
	// ExpiresAt is when the object expires, set at completion. It is nil when the
	// object has no expiry.
	ExpiresAt *time.Time
	// CreatedAt is when the object was declared.
	CreatedAt time.Time
	// UpdatedAt is when the object's row last changed.
	UpdatedAt time.Time
}

// Objects is the metadata and lifecycle seam, delivered exclusively by the
// metadata module.
//
// Every method takes the tenant from ctx and refuses with a tenant-side error
// when there is none; rows are scoped by the embedded tenant.Model and the
// statement filter is applied by the roster module's GORM plugin.
//
// The semantics each method carries are the delivering module's to keep:
//
//   - Create validates a Declaration (a positive Size, a non-empty ContentType,
//     a ChecksumSHA256 that is empty or 64 hex digits), generates the identifier
//     and the internal key, lands a pending row and opens an upload window. A
//     Declaration that fails validation is ErrInvalidRequest and lands no row.
//   - Upload requires a pending or uploaded row with an open upload window and
//     a size equal to the declared size, stores the bytes through Store and
//     records the observed size and SHA-256, moving the row to uploaded. A
//     precondition that fails is refused before any byte is written.
//   - Complete moves an uploaded row to completed and stamps its expiry; a
//     completed row is returned unchanged; any other state is ErrStateConflict.
//   - Get returns the row's view; a deleted or unknown object is
//     ErrObjectNotFound.
//   - OpenContent answers only for a completed object and returns a read-only
//     stream over its bytes; a row that says completed while the backend holds
//     no bytes is ErrContentMissing.
//   - List returns this tenant's undeleted objects in (created_at, id) order.
//   - Delete removes the bytes and tombstones the row; it is idempotent on an
//     already-deleted object.
type Objects interface {
	Create(ctx context.Context, d Declaration) (Object, error)
	Upload(ctx context.Context, id string, r io.Reader, size int64) error
	Complete(ctx context.Context, id string) (Object, error)
	Get(ctx context.Context, id string) (Object, error)
	OpenContent(ctx context.Context, id string) (io.ReadCloser, error)
	List(ctx context.Context, q ListQuery) ([]Object, error)
	Delete(ctx context.Context, id string) error
}

// Declaration is what a caller states about an object before any byte arrives.
type Declaration struct {
	// Name is the caller's own label for the object. It is opaque here.
	Name string
	// Size is the declared number of bytes. An upload whose byte count differs
	// from this is refused.
	Size int64
	// ContentType is the declared content type, recorded as the object's MIME at
	// upload.
	ContentType string
	// ChecksumSHA256 is the declared SHA-256, as 64 hex digits. It is optional:
	// an empty value declares no checksum.
	ChecksumSHA256 string
}

// ListQuery narrows and pages a List.
type ListQuery struct {
	// Limit caps the rows returned. The metadata module applies a default and an
	// upper bound.
	Limit int
	// Cursor is the keyset cursor: the encoding of the previous page's last
	// (created_at, id). An empty cursor is the first page. It is opaque to a
	// caller; its encoding is this capability's own convention.
	Cursor string
}

// The audit action type names this capability declares. An audit action is not a
// resource: it is the event type name a publisher puts on the bus, and the audit
// module names the type it watches through its own events configuration. This
// capability declares the names and publishes nothing; the host emits the event
// at the irreversible point a name describes.
const (
	// EventObjectCreated names the point at which an object has landed a pending
	// row.
	EventObjectCreated = "objectstore.object.created"
	// EventObjectCompleted names the point at which an object has become
	// readable.
	EventObjectCompleted = "objectstore.object.completed"
	// EventObjectDeleted names the point at which an object has become
	// unrecoverable.
	EventObjectDeleted = "objectstore.object.deleted"
)

var (
	// ErrObjectNotFound reports an object this tenant cannot see: an unknown
	// identifier, another tenant's object and a deleted object all take this one
	// shape, so the answer leaks nothing about existence.
	ErrObjectNotFound = errors.New("objectstore: the object is not visible to this tenant")
	// ErrStateConflict reports an action the object's current state does not
	// allow: completing an object that was never uploaded, reading one that was
	// never completed, or uploading past the upload window.
	ErrStateConflict = errors.New("objectstore: the object's state does not allow this action")
	// ErrContentMissing reports a row that says completed while the backend holds
	// no bytes for it.
	ErrContentMissing = errors.New("objectstore: the object's bytes are not in the backend")
	// ErrStoreUnavailable reports a byte seam that is absent or a backend that is
	// unreachable. A byte operation that fails keeps the backend's own error
	// wrapped inside it.
	ErrStoreUnavailable = errors.New("objectstore: the byte store is unavailable")
	// ErrInvalidConfig reports a configuration the module cannot run on: an input
	// item is missing, a value is unusable, or the module contradicts its own
	// nature.
	ErrInvalidConfig = errors.New("objectstore: the configuration holds a value the module cannot run on")
	// ErrInvalidRequest reports a request whose shape cannot be read: a
	// Declaration whose shape is illegal, or an upload whose byte count differs
	// from the declared size.
	ErrInvalidRequest = errors.New("objectstore: the request's shape cannot be read")
)
